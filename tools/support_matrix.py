#!/usr/bin/env python3
"""The support matrix (S86-04): `docs/support/clusters.yaml` is the record, `docs/deployment.md` reads it.

    uv run python tools/support_matrix.py            # writes the section between the markers
    uv run python tools/support_matrix.py --check    # fails if the section differs from the record

Each entry's word is computed from its last green proof against the record's `as_of` date (plan
2026-11-25, D4): `supported` when the proof is at most 30 days older than `as_of`, `tested` when it ran
green once (older, or its date was not recorded), `unknown` when it never ran. Nobody writes the word: a
record that does is refused, and so is a page that calls a provider supported without an entry that
computes to it (`unsupported_claims`).

`as_of` is the day the record was last brought up to date, written in the record and moved forward by
whoever records a proof (and by the scheduled proofs, S86-15): the word never changes on its own, so the
docs test never turns red on a day nobody committed anything. A record whose `as_of` is in the future,
or older than one of its proofs, is refused.
"""

from __future__ import annotations

import datetime
import pathlib
import re
import sys
from dataclasses import dataclass
from typing import Any

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
RECORD = ROOT / "docs" / "support" / "clusters.yaml"
PAGE = ROOT / "docs" / "deployment.md"
BEGIN = "<!-- support-matrix:begin (generated by `make docs-support` from docs/support/clusters.yaml) -->"
END = "<!-- support-matrix:end -->"
SUPPORTED_DAYS = 30
WORDS = ("supported", "tested", "unknown")
REQUIRED = ("id", "provider", "names", "distribution", "runtime", "network_policy", "executors", "proof")


class RecordError(ValueError):
    """The record breaks one of its rules: what, and in which entry."""


@dataclass(frozen=True)
class Entry:
    id: str
    provider: str
    names: tuple[str, ...]
    distribution: str | None
    runtime: str | None
    network_policy: str | None
    executors: tuple[str, ...]
    proved: bool
    date: datetime.date | None
    version: str | None
    what: str | None
    evidence: tuple[str, ...]

    def word(self, today: datetime.date) -> str:
        if not self.proved:
            return "unknown"
        if self.date is not None and (today - self.date).days <= SUPPORTED_DAYS:
            return "supported"
        return "tested"


def _entry(raw: Any, today: datetime.date) -> Entry:
    if not isinstance(raw, dict):
        raise RecordError(f"an entry is not a mapping: {raw!r}")
    name = raw.get("id", "?")
    if "word" in raw or (isinstance(raw.get("proof"), dict) and "word" in raw["proof"]):
        raise RecordError(f"{name}: the word is computed from the proof's date, never written in the record")
    missing = [key for key in REQUIRED if key not in raw]
    if missing:
        raise RecordError(f"{name}: missing {', '.join(missing)}")
    proof = raw["proof"]
    date: datetime.date | None = None
    if proof is not None:
        if not isinstance(proof, dict) or "date" not in proof or not proof.get("evidence"):
            raise RecordError(f"{name}: a proof has a `date` (null when not recorded) and its `evidence`")
        date = proof["date"]
        if date is not None and not isinstance(date, datetime.date):
            raise RecordError(f"{name}: the proof's date is not a date: {date!r}")
        if date is not None and date > today:
            raise RecordError(
                f"{name}: the proof is dated {date}, after the record's `as_of` ({today}): move it"
            )
    return Entry(
        id=str(raw["id"]),
        provider=str(raw["provider"]),
        names=tuple(str(n) for n in raw["names"] or ()),
        distribution=raw["distribution"],
        runtime=raw["runtime"],
        network_policy=raw["network_policy"],
        executors=tuple(str(e) for e in raw["executors"] or ()),
        proved=proof is not None,
        date=date,
        version=None if proof is None or proof.get("version") is None else str(proof["version"]),
        what=None if proof is None else proof.get("what"),
        evidence=() if proof is None else tuple(str(e) for e in proof["evidence"]),
    )


def as_of(text: str | None = None) -> datetime.date:
    """The day the record was last brought up to date: the date every word is computed against."""
    document = yaml.safe_load(RECORD.read_text(encoding="utf-8") if text is None else text) or {}
    value = document.get("as_of")
    if not isinstance(value, datetime.date):
        raise RecordError(
            "the record has no `as_of` date (YYYY-MM-DD): the words would have nothing to count from"
        )
    if value > datetime.date.today():
        raise RecordError(f"`as_of` is {value}, after today")
    return value


def load(text: str | None = None, today: datetime.date | None = None) -> list[Entry]:
    """The record's entries; `RecordError` on a broken rule."""
    today = today or as_of(text)
    document = yaml.safe_load(RECORD.read_text(encoding="utf-8") if text is None else text) or {}
    entries = [_entry(raw, today) for raw in document.get("clusters") or []]
    ids = [entry.id for entry in entries]
    if len(set(ids)) != len(ids):
        raise RecordError(f"duplicate ids: {sorted({i for i in ids if ids.count(i) > 1})}")
    return entries


def _cell(value: str | None) -> str:
    return "—" if not value else value.replace("|", "\\|")


def _evidence(item: str) -> str:
    if item.startswith("http"):
        return f"[run]({item})" if "/actions/runs/" in item else f"<{item}>"
    return f"`{item}`"


def render(entries: list[Entry], today: datetime.date | None = None) -> str:
    """The section between the markers, markers included."""
    today = today or as_of()
    lines = [
        BEGIN,
        "",
        "| Cluster | Distribution | Sandboxed runtime | NetworkPolicy engine | Executors "
        "| Last green proof | Word |",
        "| :-- | :-- | :-- | :-- | :-- | :-- | :-- |",
    ]
    for entry in entries:
        if entry.proved:
            when = str(entry.date) if entry.date else "date not recorded"
            version = f", {entry.version}" if entry.version else ""
            proof = f"{when}{version}: {entry.what or ''} ({', '.join(_evidence(e) for e in entry.evidence)})"
        else:
            proof = "never run"
        executors = ", ".join(f"`{e}`" for e in entry.executors) or "—"
        row = [
            entry.provider,
            _cell(entry.distribution),
            _cell(entry.runtime),
            _cell(entry.network_policy),
            executors,
            _cell(proof),
            f"**{entry.word(today)}**",
        ]
        lines.append("| " + " | ".join(row) + " |")
    lines += ["", END]
    return "\n".join(lines)


def section_of(page: str) -> str:
    start, end = page.find(BEGIN), page.find(END)
    if start < 0 or end < start:
        raise RecordError(f"{PAGE.name} has no support-matrix markers")
    return page[start : end + len(END)]


def write(page: str, section: str) -> str:
    return page.replace(section_of(page), section)


#: A sentence that claims support: `X is supported`, `supported on X`, `supports X`, `X (supported)`.
#: A negation (`not supported`, `unsupported`) is no claim.
_SENTENCE = re.compile(r"[^.!?\n]+[.!?]?")
_CLAIM = re.compile(r"(?<![-\w])(?:supported|supports)\b", re.IGNORECASE)
_NEGATED = re.compile(
    r"\b(?:not|n't|never|no longer)\s+(?:yet\s+|officially\s+)?supported\b|n't\s+supported\b", re.IGNORECASE
)


def unsupported_claims(text: str, entries: list[Entry], today: datetime.date | None = None) -> list[str]:
    """Each sentence of `text` that calls a provider supported while its entry does not compute to it.

    Narrow on purpose: a sentence counts only when it names one of an entry's `names` (whole words, as
    written) and says `supported` or `supports` without a negation in front."""
    today = today or as_of()
    found: list[str] = []
    for sentence in _SENTENCE.findall(text):
        if not _CLAIM.search(_NEGATED.sub("", sentence)):
            continue
        for entry in entries:
            if entry.word(today) == "supported":
                continue
            if any(re.search(rf"(?<![\w-]){re.escape(name)}(?![\w-])", sentence) for name in entry.names):
                found.append(f"{entry.id} ({entry.word(today)}): {sentence.strip()}")
    return found


def main() -> int:
    try:
        entries = load()
        page = PAGE.read_text(encoding="utf-8")
        section = render(entries)
        if "--check" in sys.argv:
            if section_of(page) != section:
                print(
                    "docs/deployment.md's support matrix differs from the record: run `make docs-support`",
                    file=sys.stderr,
                )
                return 1
            print("the support matrix of docs/deployment.md is the record's")
            return 0
        PAGE.write_text(write(page, section), encoding="utf-8")
    except RecordError as exc:
        print(f"support matrix: {exc}", file=sys.stderr)
        return 1
    print(f"wrote the support matrix of {PAGE.relative_to(ROOT)} ({len(entries)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
